def get_card_name(card_number):
    """Принимает трехзначное число и возвращает название карты."""

    #Извликаем масть (первая цифра) и достоинство (вторая и третьтя цифры)
    suit_code = card_number // 100
    rank_code = card_number % 100

    #словари для хранения названий мастей и достоинств
    suits = {
        1: "пик",
        2: "треф",
        3: "бубен",
        4: "червей"
    }

    ranks = {
        6: "шестерка",
        7: "семерка",
        8: "восьмерка",
        9: "девятка",
        10: "десятка",
        11: "валет",
        12: "дама",
        13: "король",
        14: "туз",
    }

# проверяем, существуют ли введенные коды в наших словарях
    if suit_code in suits and rank_code in ranks:
       return f"{ranks[rank_code]}{suits[suit_code]}"
    else:
         return "Ошибка: неверный код карты."

